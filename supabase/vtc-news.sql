-- =============================================================================
-- RCT MP · VTC 专属新闻（车队公告）
-- 前置：p0-hardening.sql、vtc-advanced.sql
-- 说明：车队管理层（owner / vice_owner）可发布本队新闻；所有人可读。
-- =============================================================================

begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';

do $vtcn_preflight$
begin
  if to_regclass('public.vtcs') is null then
    raise exception '预检失败：vtcs 不存在，请先执行 p0-hardening.sql / vtc-advanced.sql';
  end if;
  if not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                 where n.nspname = 'public' and p.proname = 'rct_is_vtc_manager') then
    raise exception '预检失败：rct_is_vtc_manager() 不存在，请先执行 vtc-advanced.sql';
  end if;
  raise notice 'VTC 新闻预检通过。';
end
$vtcn_preflight$;

create table if not exists public.vtc_news (
  id         bigint generated by default as identity primary key,
  vtc_id     bigint not null references public.vtcs (id) on delete cascade,
  author_id  uuid references public.profiles (id) on delete set null,
  title      text not null,
  content    text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists vtc_news_vtc_created_idx
  on public.vtc_news (vtc_id, created_at desc);

alter table public.vtc_news enable row level security;

-- 所有人可读（车队页是公开的）
drop policy if exists "vtc_news_select_public" on public.vtc_news;
create policy "vtc_news_select_public"
  on public.vtc_news
  for select
  to anon, authenticated
  using (true);

-- 只有该车队管理层可写，且作者必须是本人
drop policy if exists "vtc_news_insert_manager" on public.vtc_news;
create policy "vtc_news_insert_manager"
  on public.vtc_news
  for insert
  to authenticated
  with check (
    author_id = auth.uid()
    and public.rct_is_vtc_manager(vtc_id)
  );

drop policy if exists "vtc_news_update_manager" on public.vtc_news;
create policy "vtc_news_update_manager"
  on public.vtc_news
  for update
  to authenticated
  using (public.rct_is_vtc_manager(vtc_id))
  with check (public.rct_is_vtc_manager(vtc_id));

drop policy if exists "vtc_news_delete_manager" on public.vtc_news;
create policy "vtc_news_delete_manager"
  on public.vtc_news
  for delete
  to authenticated
  using (public.rct_is_vtc_manager(vtc_id));

-- updated_at 触发器（events.sql 里已有同名函数时复用；不存在则创建）
create or replace function public.rct_touch_updated_at()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $fn$
begin
  new.updated_at := now();
  return new;
end
$fn$;

drop trigger if exists trg_vtc_news_touch on public.vtc_news;
create trigger trg_vtc_news_touch
  before update on public.vtc_news
  for each row execute function public.rct_touch_updated_at();

commit;

-- V-VTCN-1
select c.relname, c.relrowsecurity from pg_class c
join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relname = 'vtc_news';

-- V-VTCN-2
select policyname, cmd from pg_policies
where schemaname = 'public' and tablename = 'vtc_news' order by 1;

