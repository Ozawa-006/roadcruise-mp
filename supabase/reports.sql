-- =============================================================================
-- RCT MP · 举报/申诉系统 + 论坛回复可编辑（配套守卫）
-- 前置：p0-hardening.sql（RLS/辅助函数/通知表）
-- -----------------------------------------------------------------------------
-- 1. reports 表 + RLS（本人可提交/查看自己的；Lv.40+ 可查看处理）
-- 2. 状态变化时给举报人发站内通知（type='report'）
-- 3. 允许作者编辑自己的回复（forum_replies UPDATE 策略 + 字段守卫）
-- =============================================================================

begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';

do $rep_preflight$
begin
  if to_regclass('public.profiles') is null or to_regclass('public.notifications') is null then
    raise exception '预检失败：请先执行 p0-hardening.sql';
  end if;
  if not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                 where n.nspname = 'public' and p.proname = 'rct_is_steam_verified') then
    raise exception '预检失败：rct_is_steam_verified() 不存在，请先执行 p0-hardening.sql';
  end if;
  raise notice '举报系统预检通过。';
end
$rep_preflight$;

-- =============================================================================
-- STEP 1 · reports
-- =============================================================================
create table if not exists public.reports (
  id          bigint generated by default as identity primary key,
  reporter_id uuid not null references public.profiles (id) on delete cascade,
  target_type text not null,
  target_id   text,
  target_url  text,
  reason      text not null,
  detail      text,
  status      text not null default 'open',
  handled_by  uuid references public.profiles (id) on delete set null,
  handled_at  timestamptz,
  handle_note text,
  created_at  timestamptz not null default now()
);

do $rep_checks$
begin
  if not exists (select 1 from pg_constraint where conname = 'reports_target_type_check'
                   and conrelid = 'public.reports'::regclass) then
    alter table public.reports
      add constraint reports_target_type_check
      check (target_type in ('topic', 'reply', 'profile', 'vtc', 'event', 'other'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'reports_status_check'
                   and conrelid = 'public.reports'::regclass) then
    alter table public.reports
      add constraint reports_status_check
      check (status in ('open', 'reviewing', 'resolved', 'rejected'));
  end if;
end
$rep_checks$;

create index if not exists reports_status_created_idx on public.reports (status, created_at desc);
create index if not exists reports_reporter_idx on public.reports (reporter_id, created_at desc);

alter table public.reports enable row level security;

-- 本人可看自己的；工作人员(Lv.40+)可看全部
drop policy if exists "reports_select_own_or_staff" on public.reports;
create policy "reports_select_own_or_staff"
  on public.reports
  for select
  to authenticated
  using (reporter_id = auth.uid() or public.rct_role_level() >= 40);

-- 提交：必须登录 + 已完成 Steam 验证，且 reporter_id = 本人
drop policy if exists "reports_insert_own_verified" on public.reports;
create policy "reports_insert_own_verified"
  on public.reports
  for insert
  to authenticated
  with check (
    reporter_id = auth.uid()
    and public.rct_is_steam_verified()
  );

-- 处理：工作人员(Lv.40+)可更新状态/处理人/备注
drop policy if exists "reports_update_staff" on public.reports;
create policy "reports_update_staff"
  on public.reports
  for update
  to authenticated
  using (public.rct_role_level() >= 40)
  with check (public.rct_role_level() >= 40);

-- 不提供 DELETE 策略（举报记录保留）

-- =============================================================================
-- STEP 2 · 状态变化通知举报人
-- =============================================================================
create or replace function public.rct_reports_notify()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_label text;
begin
  if new.status is not distinct from old.status then
    return new;
  end if;

  v_label := case new.status
    when 'reviewing' then '处理中'
    when 'resolved'  then '已处理'
    when 'rejected'  then '未通过'
    else new.status
  end;

  insert into public.notifications (user_id, actor_id, type, content, link, is_read)
  values (
    new.reporter_id,
    new.handled_by,
    'report',
    '你提交的举报状态已更新为：' || v_label,
    '/reports',
    false
  );

  return new;
end
$fn$;

drop trigger if exists trg_reports_notify on public.reports;
create trigger trg_reports_notify
  after update on public.reports
  for each row execute function public.rct_reports_notify();

-- handled_at 自动填时间
create or replace function public.rct_reports_touch_handled()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $fn$
begin
  if new.status is distinct from old.status and new.status in ('reviewing', 'resolved', 'rejected') then
    new.handled_at := now();
    if new.handled_by is null then
      new.handled_by := auth.uid();
    end if;
  end if;
  return new;
end
$fn$;

drop trigger if exists trg_reports_touch_handled on public.reports;
create trigger trg_reports_touch_handled
  before update on public.reports
  for each row execute function public.rct_reports_touch_handled();

-- =============================================================================
-- STEP 3 · 论坛回复可编辑（作者本人可改内容；staff 可改；锁 topic_id/author_id）
-- =============================================================================
drop policy if exists "forum_replies_update_author_or_manager" on public.forum_replies;
create policy "forum_replies_update_author_or_manager"
  on public.forum_replies
  for update
  to authenticated
  using (author_id = auth.uid() or public.rct_role_level() >= 70)
  with check (author_id = auth.uid() or public.rct_role_level() >= 70);

create or replace function public.rct_guard_forum_replies()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
begin
  if public.rct_caller_is_backend() then
    return new;
  end if;

  -- 非经理以下：回复的归属、主题、创建时间不可改，只能编辑内容
  if public.rct_role_level() < 70 then
    new.topic_id   := old.topic_id;
    new.author_id  := old.author_id;
    new.created_at := old.created_at;
  end if;

  return new;
end
$fn$;

drop trigger if exists trg_rct_guard_forum_replies on public.forum_replies;
create trigger trg_rct_guard_forum_replies
  before update on public.forum_replies
  for each row execute function public.rct_guard_forum_replies();

commit;

-- V-REP-1
select c.relname, c.relrowsecurity from pg_class c
join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relname = 'reports';

-- V-REP-2
select policyname, cmd from pg_policies
where schemaname = 'public' and tablename = 'reports' order by 1;

-- V-REP-3
select tgname, tgrelid::regclass::text as tbl
from pg_trigger where tgname in ('trg_reports_notify', 'trg_reports_touch_handled', 'trg_rct_guard_forum_replies')
order by 1;

