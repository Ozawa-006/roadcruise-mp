-- =============================================================================
-- RCT MP · 活动系统（events）+ P1 收尾（custom_id 唯一/格式约束）
-- 项目：https://www.roadcruise-mp.com  /  Supabase project ref: undmtiotuffrqcfvqand
-- 前置：已执行 supabase/p0-hardening.sql（RLS/守卫/辅助函数）
-- -----------------------------------------------------------------------------
-- 内容：
--   1. events / event_registrations 两张表 + RLS + 报名人数统计视图
--   2. 报名/取消报名 RPC（名额校验、Steam 验证、重复报名处理）
--   3. updated_at 自动刷新触发器
--   4. custom_id 格式约束 + 部分唯一索引（P1 收尾）
-- -----------------------------------------------------------------------------
-- 执行：先备份 → 把末尾 commit; 改 rollback; 预演 → 无报错再改回 commit; 执行。
-- =============================================================================

begin;

set local lock_timeout = '5s';
set local statement_timeout = '60s';

-- =============================================================================
-- STEP 0 · 预检
-- =============================================================================
do $ev_preflight$
begin
  if to_regclass('public.profiles') is null then
    raise exception '预检失败：profiles 不存在，请先执行 p0-hardening.sql';
  end if;
  if not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                 where n.nspname = 'public' and p.proname = 'rct_is_steam_verified') then
    raise exception '预检失败：rct_is_steam_verified() 不存在，请先执行 p0-hardening.sql';
  end if;
  raise notice '活动系统预检通过。';
end
$ev_preflight$;


-- =============================================================================
-- STEP 1 · events / event_registrations
-- =============================================================================
create table if not exists public.events (
  id          bigint generated by default as identity primary key,
  title       text not null,
  description text not null default '',
  start_at    timestamptz not null,
  end_at      timestamptz,
  location    text,
  server_id   text,
  capacity    integer,
  image_url   text,
  status      text not null default 'draft',
  created_by  uuid references public.profiles (id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

do $ev_checks$
begin
  if not exists (select 1 from pg_constraint where conname = 'events_status_check'
                   and conrelid = 'public.events'::regclass) then
    alter table public.events
      add constraint events_status_check check (status in ('draft', 'published', 'cancelled'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'events_capacity_check'
                   and conrelid = 'public.events'::regclass) then
    alter table public.events
      add constraint events_capacity_check check (capacity is null or capacity > 0);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'events_time_check'
                   and conrelid = 'public.events'::regclass) then
    alter table public.events
      add constraint events_time_check check (end_at is null or end_at >= start_at);
  end if;
end
$ev_checks$;

create index if not exists events_status_start_idx on public.events (status, start_at);
create index if not exists events_start_idx on public.events (start_at desc);
create index if not exists events_created_by_idx on public.events (created_by);

create table if not exists public.event_registrations (
  id         bigint generated by default as identity primary key,
  event_id   bigint not null references public.events (id) on delete cascade,
  user_id    uuid not null references public.profiles (id) on delete cascade,
  status     text not null default 'registered',
  note       text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (event_id, user_id)
);

do $ev_reg_checks$
begin
  if not exists (select 1 from pg_constraint where conname = 'event_registrations_status_check'
                   and conrelid = 'public.event_registrations'::regclass) then
    alter table public.event_registrations
      add constraint event_registrations_status_check check (status in ('registered', 'cancelled'));
  end if;
end
$ev_reg_checks$;

create index if not exists event_registrations_user_idx
  on public.event_registrations (user_id, status);
create index if not exists event_registrations_event_idx
  on public.event_registrations (event_id, status);

alter table public.events              enable row level security;
alter table public.event_registrations enable row level security;

-- 活动：匿名只读已发布；工作人员(Lv.40+)可读写全部
drop policy if exists "events_select_published_or_staff" on public.events;
create policy "events_select_published_or_staff"
  on public.events
  for select
  to anon, authenticated
  using (status = 'published' or public.rct_role_level() >= 40);

drop policy if exists "events_insert_staff" on public.events;
create policy "events_insert_staff"
  on public.events
  for insert
  to authenticated
  with check (public.rct_role_level() >= 40);

drop policy if exists "events_update_staff" on public.events;
create policy "events_update_staff"
  on public.events
  for update
  to authenticated
  using (public.rct_role_level() >= 40)
  with check (public.rct_role_level() >= 40);

drop policy if exists "events_delete_staff" on public.events;
create policy "events_delete_staff"
  on public.events
  for delete
  to authenticated
  using (public.rct_role_level() >= 40);

-- 报名：本人或工作人员可读；本人可写（但仍需通过 RPC 才校验名额/时间）
drop policy if exists "event_registrations_select_own_or_staff" on public.event_registrations;
create policy "event_registrations_select_own_or_staff"
  on public.event_registrations
  for select
  to authenticated
  using (user_id = auth.uid() or public.rct_role_level() >= 40);

drop policy if exists "event_registrations_insert_own" on public.event_registrations;
create policy "event_registrations_insert_own"
  on public.event_registrations
  for insert
  to authenticated
  with check (user_id = auth.uid() and public.rct_is_steam_verified());

drop policy if exists "event_registrations_update_own" on public.event_registrations;
create policy "event_registrations_update_own"
  on public.event_registrations
  for update
  to authenticated
  using (user_id = auth.uid() or public.rct_role_level() >= 40)
  with check (user_id = auth.uid() or public.rct_role_level() >= 40);

-- 公开的报名人数（不暴露报名者身份）：SECURITY DEFINER 视图
create or replace view public.event_registration_counts
with (security_invoker = false) as
select event_id,
       count(*) filter (where status = 'registered')::int as registered_count
from public.event_registrations
group by event_id;

comment on view public.event_registration_counts is
  'RCT MP：活动报名人数（公开只读，不暴露报名者身份）。';

grant select on public.event_registration_counts to anon, authenticated, service_role;


-- =============================================================================
-- STEP 2 · updated_at 自动刷新
-- =============================================================================
create or replace function public.rct_touch_updated_at()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $fn$
begin
  new.updated_at := now();
  return new;
end
$fn$;

drop trigger if exists trg_events_touch on public.events;
create trigger trg_events_touch
  before update on public.events
  for each row execute function public.rct_touch_updated_at();

drop trigger if exists trg_event_registrations_touch on public.event_registrations;
create trigger trg_event_registrations_touch
  before update on public.event_registrations
  for each row execute function public.rct_touch_updated_at();


-- =============================================================================
-- STEP 3 · 报名 / 取消报名 RPC
-- =============================================================================
create or replace function public.rct_event_register(p_event_id bigint, p_note text default null)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_uid      uuid := auth.uid();
  v_status   text;
  v_start    timestamptz;
  v_cap      integer;
  v_cur      text;
  v_exists   boolean;
  v_count    integer;
begin
  if v_uid is null then raise exception '请先登录' using errcode = '42501'; end if;
  if not public.rct_is_steam_verified() then
    raise exception '未完成 Steam 正版验证，不能报名活动' using errcode = '42501';
  end if;

  select e.status, e.start_at, e.capacity
    into v_status, v_start, v_cap
  from public.events e
  where e.id = p_event_id
  for update;
  if not found then raise exception '活动不存在'; end if;
  if v_status <> 'published' then raise exception '该活动尚未发布或已取消'; end if;
  if v_start <= now() then raise exception '该活动已开始，无法报名'; end if;

  select r.status into v_cur
  from public.event_registrations r
  where r.event_id = p_event_id and r.user_id = v_uid;
  v_exists := found;

  if v_cur = 'registered' then
    raise exception '你已报名该活动';
  end if;

  if v_cap is not null then
    select count(*) into v_count
    from public.event_registrations r
    where r.event_id = p_event_id and r.status = 'registered';
    if v_count >= v_cap then
      raise exception '活动名额已满';
    end if;
  end if;

  if v_exists then
    update public.event_registrations
       set status = 'registered',
           note = nullif(btrim(coalesce(p_note, '')), '')
     where event_id = p_event_id and user_id = v_uid;
  else
    insert into public.event_registrations (event_id, user_id, status, note)
    values (p_event_id, v_uid, 'registered', nullif(btrim(coalesce(p_note, '')), ''));
  end if;

  return jsonb_build_object('ok', true, 'status', 'registered');
end
$fn$;

create or replace function public.rct_event_cancel(p_event_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_uid uuid := auth.uid();
begin
  if v_uid is null then raise exception '请先登录' using errcode = '42501'; end if;
  update public.event_registrations
     set status = 'cancelled'
   where event_id = p_event_id and user_id = v_uid and status = 'registered';
  if not found then raise exception '你尚未报名该活动'; end if;
  return jsonb_build_object('ok', true, 'status', 'cancelled');
end
$fn$;

do $ev_grants$
begin
  execute 'revoke all on function public.rct_event_register(bigint, text) from public';
  execute 'grant execute on function public.rct_event_register(bigint, text) to authenticated, service_role';
  execute 'revoke all on function public.rct_event_cancel(bigint) from public';
  execute 'grant execute on function public.rct_event_cancel(bigint) to authenticated, service_role';
  raise notice '活动 RPC 权限已收紧。';
end
$ev_grants$;


-- =============================================================================
-- STEP 4 · P1 收尾：custom_id 格式约束 + 唯一索引
-- =============================================================================
do $custom_id$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'profiles_custom_id_format'
      and conrelid = 'public.profiles'::regclass
  ) then
    -- 先检查历史数据是否合规，不合规就阻断，避免加约束失败后整份回滚
    if exists (
      select 1 from public.profiles
      where custom_id is not null and custom_id !~ '^[0-9]{4,8}$'
    ) then
      raise exception 'custom_id 存在不合规历史数据（要求 4-8 位数字），请先清理后再执行';
    end if;
    alter table public.profiles
      add constraint profiles_custom_id_format
      check (custom_id is null or custom_id ~ '^[0-9]{4,8}$');
    raise notice '已添加 profiles.custom_id 格式约束（4-8 位数字）';
  else
    raise notice 'profiles.custom_id 格式约束已存在';
  end if;
end
$custom_id$;

-- 重复的 custom_id 会阻断唯一索引；先检查
do $custom_id_unique$
declare
  v_dup integer;
begin
  select count(*) into v_dup
  from (
    select custom_id from public.profiles
    where custom_id is not null
    group by custom_id having count(*) > 1
  ) d;

  if v_dup > 0 then
    raise exception 'custom_id 存在 % 组重复，请先清理后再建唯一索引', v_dup;
  end if;

  if not exists (
    select 1 from pg_index i
    join pg_class c on c.oid = i.indrelid
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relname = 'profiles'
      and i.indisunique
      and pg_get_indexdef(i.indexrelid) like '%(custom_id)%'
  ) then
    create unique index if not exists profiles_custom_id_unique
      on public.profiles (custom_id) where custom_id is not null;
    raise notice '已创建 profiles.custom_id 部分唯一索引';
  else
    raise notice 'profiles.custom_id 唯一索引已存在';
  end if;
end
$custom_id_unique$;


-- =============================================================================
-- 校验
-- =============================================================================
commit;

-- V-EV-1 · 表与 RLS
select c.relname as table_name, c.relrowsecurity as rls_enabled
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relname in ('events', 'event_registrations')
order by 1;

-- V-EV-2 · 策略
select tablename, policyname, cmd
from pg_policies
where schemaname = 'public' and tablename in ('events', 'event_registrations')
order by tablename, policyname;

-- V-EV-3 · RPC
select p.proname, p.prosecdef as security_definer
from pg_proc p join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'public' and p.proname like 'rct_event_%'
order by 1;

-- V-EV-4 · 视图可被 anon 读
select * from public.event_registration_counts limit 5;

-- V-EV-5 · custom_id 约束/索引
select conname, pg_get_constraintdef(oid) as def
from pg_constraint where conrelid = 'public.profiles'::regclass
  and conname = 'profiles_custom_id_format';

select indexname, indexdef from pg_indexes
where schemaname = 'public' and indexname = 'profiles_custom_id_unique';

