-- =============================================================================
-- STEP 1 · 内容编辑历史（帖子/回复）
-- =============================================================================
create table if not exists public.content_edits (
  id          bigint generated by default as identity primary key,
  content_type text not null,
  content_id  bigint not null,
  editor_id   uuid references public.profiles (id) on delete set null,
  old_title   text,
  old_content text,
  new_title   text,
  new_content text,
  created_at  timestamptz not null default now()
);

do $ce_checks$
begin
  if not exists (select 1 from pg_constraint where conname='content_edits_type_check'
                   and conrelid='public.content_edits'::regclass) then
    alter table public.content_edits
      add constraint content_edits_type_check
      check (content_type in ('topic','reply'));
  end if;
end
$ce_checks$;

create index if not exists content_edits_target_idx
  on public.content_edits (content_type, content_id, created_at desc);

alter table public.content_edits enable row level security;

drop policy if exists "content_edits_select_public" on public.content_edits;
create policy "content_edits_select_public"
  on public.content_edits
  for select
  to anon, authenticated
  using (true);

grant select on public.content_edits to anon, authenticated;

create or replace function public.rct_record_content_edit()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
begin
  if tg_table_name = 'forum_topics' then
    if new.title is not distinct from old.title
       and new.content is not distinct from old.content then
      return new;
    end if;
    insert into public.content_edits
      (content_type, content_id, editor_id, old_title, old_content, new_title, new_content)
    values
      ('topic', new.id, auth.uid(), old.title, old.content, new.title, new.content);
  elsif tg_table_name = 'forum_replies' then
    if new.content is not distinct from old.content then
      return new;
    end if;
    insert into public.content_edits
      (content_type, content_id, editor_id, old_content, new_content)
    values
      ('reply', new.id, auth.uid(), old.content, new.content);
  end if;
  return new;
end
$fn$;

drop trigger if exists trg_content_edit_topics on public.forum_topics;
create trigger trg_content_edit_topics
  after update on public.forum_topics
  for each row execute function public.rct_record_content_edit();

drop trigger if exists trg_content_edit_replies on public.forum_replies;
create trigger trg_content_edit_replies
  after update on public.forum_replies
  for each row execute function public.rct_record_content_edit();

-- =============================================================================
-- STEP 2 · 举报超时升级
-- =============================================================================
alter table public.reports
  add column if not exists notify_stage integer not null default 0;
alter table public.reports
  add column if not exists last_notified_at timestamptz;

create or replace function public.rct_reports_escalate()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  r record;
  v_count integer := 0;
  v_remind integer := 0;
begin
  for r in
    select id, target_type, target_id, reason, created_at, notify_stage, last_notified_at
    from public.reports
    where status in ('open', 'reviewing')
      and created_at <= now() - interval '24 hours'
  loop
    if r.notify_stage = 0 then
      insert into public.notifications (user_id, actor_id, type, content, link, is_read)
      select p.id, null, 'report',
             '举报超 24 小时未处理：' || coalesce(r.reason, ''),
             '/admin/reports',
             false
      from public.profiles p
      where p.role_level >= 70;

      update public.reports
         set notify_stage = 1, last_notified_at = now()
       where id = r.id;
      v_count := v_count + 1;

    elsif r.notify_stage = 1 and r.created_at <= now() - interval '48 hours' then
      insert into public.notifications (user_id, actor_id, type, content, link, is_read)
      select p.id, null, 'report',
             '举报超 48 小时未处理，已升级：' || coalesce(r.reason, ''),
             '/admin/reports',
             false
      from public.profiles p
      where p.role_level >= 90;

      update public.reports
         set notify_stage = 2, last_notified_at = now()
       where id = r.id;
      v_count := v_count + 1;

    elsif r.notify_stage = 2
          and r.created_at <= now() - interval '72 hours'
          and (r.last_notified_at is null or r.last_notified_at <= now() - interval '24 hours') then
      insert into public.notifications (user_id, actor_id, type, content, link, is_read)
      select p.id, null, 'report',
             '举报仍未处理（超 72 小时）：' || coalesce(r.reason, ''),
             '/admin/reports',
             false
      from public.profiles p
      where p.role_level >= 90;

      update public.reports set last_notified_at = now() where id = r.id;
      v_remind := v_remind + 1;
    end if;
  end loop;

  return jsonb_build_object('ok', true, 'escalated', v_count, 'reminded', v_remind);
end
$fn$;

-- =============================================================================
-- STEP 3 · 站点 Cron 汇总（招募 + 举报）
-- =============================================================================
create or replace function public.rct_site_cron()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_recruitment jsonb;
  v_reports jsonb;
begin
  v_recruitment := public.rct_recruitment_cron();
  v_reports := public.rct_reports_escalate();
  return jsonb_build_object('ok', true, 'recruitment', v_recruitment, 'reports', v_reports);
end
$fn$;

do $cron_reschedule$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    begin
      perform cron.unschedule('rct-recruitment-hourly');
    exception when others then
      null;
    end;
    begin
      perform cron.unschedule('rct-site-hourly');
    exception when others then
      null;
    end;
    perform cron.schedule('rct-site-hourly', '0 * * * *', 'select public.rct_site_cron()');
    raise notice '已切换到 rct-site-hourly（每小时：招募 + 举报升级）';
  end if;
end
$cron_reschedule$;

do $cron_grants$
begin
  execute 'revoke all on function public.rct_reports_escalate() from public';
  execute 'grant execute on function public.rct_reports_escalate() to service_role';
  execute 'revoke all on function public.rct_site_cron() from public';
  execute 'grant execute on function public.rct_site_cron() to service_role';
end
$cron_grants$;

commit;

