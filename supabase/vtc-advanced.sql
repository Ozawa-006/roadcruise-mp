-- 4.5 退出车队（队长不能直接退，需先转让/解散）
create or replace function public.rct_vtc_leave()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_uid   uuid := auth.uid();
  v_role  text;
  v_vtc   bigint;
  v_owner uuid;
begin
  if v_uid is null then raise exception '请先登录' using errcode = '42501'; end if;

  select p.vtc_role, p.vtc_id into v_role, v_vtc from public.profiles p where p.id = v_uid;
  if v_vtc is null then raise exception '你当前不在任何车队'; end if;

  select v.owner_id into v_owner from public.vtcs v where v.id = v_vtc;
  if v_owner = v_uid or v_role = 'owner' then
    raise exception '车队所有者不能直接退出，请先转让或解散车队';
  end if;

  update public.profiles set vtc_id = null, vtc_role = null where id = v_uid;
  update public.vtc_applications set status = 'cancelled' where user_id = v_uid and status = 'pending';

  return jsonb_build_object('ok', true);
end
$fn$;

-- 4.6 邀请成员（车队管理层）
create or replace function public.rct_vtc_invite(p_user_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_uid   uuid := auth.uid();
  v_vtc   bigint;
  v_role  text;
begin
  if v_uid is null then raise exception '请先登录' using errcode = '42501'; end if;
  if p_user_id = v_uid then raise exception '不能邀请自己'; end if;

  select p.vtc_id, p.vtc_role into v_vtc, v_role from public.profiles p where p.id = v_uid;
  if v_vtc is null then raise exception '你不在车队中'; end if;
  if v_role not in ('owner', 'vice_owner') then
    raise exception '只有队长/副队长可以邀请成员' using errcode = '42501';
  end if;

  if not exists (select 1 from public.profiles p where p.id = p_user_id) then
    raise exception '被邀请的用户不存在';
  end if;
  if exists (select 1 from public.profiles p where p.id = p_user_id and p.vtc_id is not null) then
    raise exception '该玩家已在车队中';
  end if;
  if exists (select 1 from public.vtc_invitations i where i.vtc_id = v_vtc and i.invited_user_id = p_user_id and i.status = 'pending') then
    raise exception '已经邀请过该玩家，等待对方响应';
  end if;

  insert into public.vtc_invitations (vtc_id, invited_user_id, invited_by)
  values (v_vtc, p_user_id, v_uid);

  insert into public.notifications (user_id, actor_id, type, content, link, is_read)
  values (p_user_id, v_uid, 'vtc', '你收到一条车队邀请', '/vtc/' || v_vtc::text, false);

  return jsonb_build_object('ok', true);
end
$fn$;

-- 4.7 响应邀请（被邀请人）
create or replace function public.rct_vtc_respond_invite(p_id bigint, p_accept boolean)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_uid    uuid := auth.uid();
  v_vtc    bigint;
  v_status text;
  v_by     uuid;
  v_cur    bigint;
begin
  if v_uid is null then raise exception '请先登录' using errcode = '42501'; end if;

  select i.vtc_id, i.status, i.invited_by
    into v_vtc, v_status, v_by
  from public.vtc_invitations i
  where i.id = p_id and i.invited_user_id = v_uid
  for update;
  if not found then raise exception '邀请不存在'; end if;
  if v_status <> 'pending' then raise exception '该邀请已处理'; end if;

  if p_accept then
    if not public.rct_is_steam_verified() then
      raise exception '未完成 Steam 正版验证，不能加入车队' using errcode = '42501';
    end if;
    select p.vtc_id into v_cur from public.profiles p where p.id = v_uid;
    if v_cur is not null then raise exception '你已经在车队中'; end if;

    perform set_config('rct.vtc_admin', 'on', true);
    update public.profiles set vtc_id = v_vtc, vtc_role = 'member' where id = v_uid;
    perform set_config('rct.vtc_admin', 'off', true);

    update public.vtc_invitations set status = 'accepted', responded_at = now() where id = p_id;

    if v_by is not null then
      insert into public.notifications (user_id, actor_id, type, content, link, is_read)
      values (v_by, v_uid, 'vtc', '你邀请的玩家已加入车队', '/vtc/' || v_vtc::text, false);
    end if;
  else
    update public.vtc_invitations set status = 'declined', responded_at = now() where id = p_id;
  end if;

  return jsonb_build_object('ok', true);
end
$fn$;

-- 4.8 踢出成员（管理层；不能踢队长）
create or replace function public.rct_vtc_kick(p_user_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_uid    uuid := auth.uid();
  v_vtc    bigint;
  v_role   text;
  v_target bigint;
  v_trole  text;
  v_owner  uuid;
begin
  if v_uid is null then raise exception '请先登录' using errcode = '42501'; end if;

  select p.vtc_id, p.vtc_role into v_vtc, v_role from public.profiles p where p.id = v_uid;
  if v_vtc is null or v_role not in ('owner', 'vice_owner') then
    raise exception '只有队长/副队长可以踢人' using errcode = '42501';
  end if;
  if p_user_id = v_uid then raise exception '不能踢自己，请使用退出车队'; end if;

  select p.vtc_id, p.vtc_role into v_target, v_trole from public.profiles p where p.id = p_user_id;
  if v_target is distinct from v_vtc then raise exception '该玩家不在你的车队'; end if;
  if v_trole = 'owner' then raise exception '不能踢出车队所有者'; end if;

  select v.owner_id into v_owner from public.vtcs v where v.id = v_vtc;

  perform set_config('rct.vtc_admin', 'on', true);
  update public.profiles set vtc_id = null, vtc_role = null where id = p_user_id;
  perform set_config('rct.vtc_admin', 'off', true);

  update public.vtc_applications set status = 'cancelled' where user_id = p_user_id and status = 'pending';

  insert into public.notifications (user_id, actor_id, type, content, link, is_read)
  values (p_user_id, v_uid, 'vtc', '你已被移出车队', '/vtc/' || v_vtc::text, false);

  return jsonb_build_object('ok', true);
end
$fn$;

-- 4.9 设置成员职位（仅队长；可设 vice_owner / dispatcher / member）
create or replace function public.rct_vtc_set_role(p_user_id uuid, p_role text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_uid    uuid := auth.uid();
  v_vtc    bigint;
  v_target bigint;
  v_owner  uuid;
begin
  if v_uid is null then raise exception '请先登录' using errcode = '42501'; end if;
  if p_role not in ('vice_owner', 'dispatcher', 'member') then
    raise exception '非法职位：%，只允许 vice_owner / dispatcher / member', p_role;
  end if;

  select p.vtc_id into v_vtc from public.profiles p where p.id = v_uid;
  if v_vtc is null then raise exception '你不在车队中'; end if;

  select v.owner_id into v_owner from public.vtcs v where v.id = v_vtc;
  if v_owner is distinct from v_uid then
    raise exception '只有车队所有者可以任命职位' using errcode = '42501';
  end if;

  select p.vtc_id into v_target from public.profiles p where p.id = p_user_id;
  if v_target is distinct from v_vtc then raise exception '该玩家不在你的车队'; end if;
  if p_user_id = v_uid then raise exception '不能修改自己的职位'; end if;

  perform set_config('rct.vtc_admin', 'on', true);
  update public.profiles set vtc_role = p_role where id = p_user_id;
  perform set_config('rct.vtc_admin', 'off', true);

  return jsonb_build_object('ok', true);
end
$fn$;

-- 4.10 转让车队（仅当前队长；新队长必须是本队成员）
create or replace function public.rct_vtc_transfer(p_new_owner uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_uid   uuid := auth.uid();
  v_vtc   bigint;
  v_owner uuid;
  v_new   bigint;
begin
  if v_uid is null then raise exception '请先登录' using errcode = '42501'; end if;
  if p_new_owner = v_uid then raise exception '不能转让给自己'; end if;

  select p.vtc_id into v_vtc from public.profiles p where p.id = v_uid;
  if v_vtc is null then raise exception '你不在车队中'; end if;

  select v.owner_id into v_owner from public.vtcs v where v.id = v_vtc;
  if v_owner is distinct from v_uid then
    raise exception '只有车队所有者可以转让车队' using errcode = '42501';
  end if;

  select p.vtc_id into v_new from public.profiles p where p.id = p_new_owner;
  if v_new is distinct from v_vtc then raise exception '新队长必须是本队成员'; end if;

  perform set_config('rct.vtc_admin', 'on', true);
  update public.profiles set vtc_role = 'member' where id = v_uid;
  update public.profiles set vtc_role = 'owner'  where id = p_new_owner;
  perform set_config('rct.vtc_admin', 'off', true);

  update public.vtcs set owner_id = p_new_owner where id = v_vtc;

  insert into public.notifications (user_id, actor_id, type, content, link, is_read)
  values (p_new_owner, v_uid, 'vtc', '你已成为车队的新任队长', '/vtc/' || v_vtc::text, false);

  return jsonb_build_object('ok', true);
end
$fn$;

-- 4.11 解散车队（仅队长；需确认字符串 DISSOLVE）
create or replace function public.rct_vtc_dissolve(p_confirm text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_uid   uuid := auth.uid();
  v_vtc   bigint;
  v_owner uuid;
  rec     record;
begin
  if v_uid is null then raise exception '请先登录' using errcode = '42501'; end if;
  if coalesce(p_confirm, '') <> 'DISSOLVE' then
    raise exception '解散确认字符串不正确（需要 DISSOLVE）';
  end if;

  select p.vtc_id into v_vtc from public.profiles p where p.id = v_uid;
  if v_vtc is null then raise exception '你不在车队中'; end if;

  select v.owner_id into v_owner from public.vtcs v where v.id = v_vtc;
  if v_owner is distinct from v_uid then
    raise exception '只有车队所有者可以解散车队' using errcode = '42501';
  end if;

  -- 先通知成员（车队删除后 link 会失效，所以通知里用文本说明）
  for rec in
    select p.id from public.profiles p where p.vtc_id = v_vtc and p.id <> v_uid
  loop
    insert into public.notifications (user_id, actor_id, type, content, link, is_read)
    values (rec.id, v_uid, 'vtc', '你所在的车队已被解散', null, false);
  end loop;

  perform set_config('rct.vtc_admin', 'on', true);
  update public.profiles set vtc_id = null, vtc_role = null where vtc_id = v_vtc;
  perform set_config('rct.vtc_admin', 'off', true);

  delete from public.vtcs where id = v_vtc;

  return jsonb_build_object('ok', true);
end
$fn$;

-- 只允许登录用户调用这些 RPC（anon 不可调用；内部仍会校验 auth.uid）
do $vtc_grants$
declare
  fn text;
begin
  foreach fn in array array[
    'public.rct_vtc_apply(bigint, text)',
    'public.rct_vtc_cancel_application(bigint)',
    'public.rct_vtc_review_application(bigint, boolean)',
    'public.rct_vtc_join_open(bigint)',
    'public.rct_vtc_leave()',
    'public.rct_vtc_invite(uuid)',
    'public.rct_vtc_respond_invite(bigint, boolean)',
    'public.rct_vtc_kick(uuid)',
    'public.rct_vtc_set_role(uuid, text)',
    'public.rct_vtc_transfer(uuid)',
    'public.rct_vtc_dissolve(text)'
  ]
  loop
    execute 'revoke all on function ' || fn || ' from public';
    execute 'grant execute on function ' || fn || ' to authenticated, service_role';
  end loop;
  raise notice 'VTC RPC 权限已收紧（仅 authenticated/service_role）。';
end
$vtc_grants$;


-- =============================================================================
-- STEP 5 · 升级守卫触发器：支持新职位 + RPC 管理开关
-- ⚠️ 与本文件新增的 RPC 配套；不替换会导致审批/踢人/转让被守卫拒绝。
-- =============================================================================
create or replace function public.rct_guard_profiles()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_uid        uuid := auth.uid();
  v_vtc_admin  boolean := coalesce(current_setting('rct.vtc_admin', true), '') = 'on';
  v_level      integer;
  v_old_level  integer := coalesce(old.role_level, 0);
  v_vtc_owner  uuid;
  v_old_vtc_owner uuid;
  v_recruiting boolean;
begin
  -- 3.4.1 后端 / 运维通道
  if public.rct_caller_is_backend() then
    return new;
  end if;

  -- 3.4.2 无登录态：anon key 直接 update 一律拒绝
  if v_uid is null then
    raise exception 'profiles: 未登录，禁止修改'
      using errcode = '42501';
  end if;

  -- 3.4.2b 主键不可改：防止经理把低等级用户的 id 改成别的 auth 用户 id（数据错位/DoS）
  if new.id is distinct from old.id then
    raise exception 'profiles: 不允许修改主键 id'
      using errcode = '42501';
  end if;

  v_level := public.rct_role_level();

  -- 3.4.3 Steam 验证字段：连工作人员也不能写，只能由服务端绑定接口用
  --       service_role 写入（上面 3.4.1 已经把后端通道放行了）。
  --       原因：这是“正版 ETS2 + 2 小时”门槛的唯一凭证，不能被人为代签。
  if new.steam_id is distinct from old.steam_id
     or new.steam_verified is distinct from old.steam_verified then
    raise exception 'steam_id / steam_verified 只能由服务端 Steam 绑定接口（service_role）写入，客户端不可修改'
      using errcode = '42501';
  end if;

  -- 3.4.5 其它身份字段
  if new.role            is distinct from old.role
     or new.role_level   is distinct from old.role_level
     or new.custom_id    is distinct from old.custom_id
     or new.random_id    is distinct from old.random_id
     or new.discord_id   is distinct from old.discord_id then

    if v_level < 40 then
      raise exception '权限不足：role / role_level / custom_id / random_id / discord_id 仅工作人员(Lv.40)及以上可修改'
        using errcode = '42501';
    end if;

    if old.id = v_uid then
      -- 自己改自己：只放行 custom_id（后台「我的靓号」功能，见 app/admin/users/page.tsx
      -- 的 isSelf 分支，它只提交 custom_id）。其余提权相关字段一律拒绝。
      if new.role          is distinct from old.role
         or new.role_level is distinct from old.role_level
         or new.random_id  is distinct from old.random_id
         or new.discord_id is distinct from old.discord_id then
        raise exception '禁止修改自己的 role / role_level / random_id / discord_id；只能改自己的 custom_id，或请其他工作人员/service_role 操作'
          using errcode = '42501';
      end if;
    else
      -- 改别人：不能动同级或上级，不能授予同级或更高等级
      -- 例外：Lv.100 开发者（交接文档“无视任何限制”，且前端 UI 也允许开发者互相管理）
      if v_old_level >= v_level and v_level < 100 then
        raise exception '禁止修改同级或上级的身份字段（目标 Lv.%，你的 Lv.%）', v_old_level, v_level
          using errcode = '42501';
      end if;

      if v_level < 100
         and new.role_level is distinct from old.role_level
         and new.role_level >= v_level then
        raise exception '禁止赋予同级或更高的等级（目标 Lv.%，你的 Lv.%）', new.role_level, v_level
          using errcode = '42501';
      end if;

      -- 若 roles 表已定义职位等级，再校验一次“职位等级低于自己”
      if v_level < 100
         and new.role is distinct from old.role
         and exists (
           select 1
           from public.roles r
           where r.name = new.role
             and coalesce(r.level, 0) >= v_level
         ) then
        raise exception '禁止赋予同级或更高的职位：%', coalesce(new.role, '(null)')
          using errcode = '42501';
      end if;
    end if;
  end if;

  -- 3.4.6 车队字段
  -- ⚠️ 车队管理 RPC（rct_vtc_*）在事务内 set_config('rct.vtc_admin','on',true) 后
  --    执行跨用户的车队字段变更；普通客户端无法在同一个 PostgREST 请求里设置该 GUC。
  if v_vtc_admin then
    return new;
  end if;
  if new.vtc_id is distinct from old.vtc_id
     or new.vtc_role is distinct from old.vtc_role then

    -- owner 不能通过客户端把自己摘出车队（否则车队会变成无主孤儿；
    -- 转让/解散目前没有产品功能，需 service_role / SQL Editor 操作）
    -- 所有者保护以 vtcs.owner_id 为准（不能只信 profiles.vtc_role）：
    -- 否则车主可以“先把 vtc_role 改成 member、再退出”，把车队变成无主孤儿。
    if old.vtc_id is not null then
      select v.owner_id into v_old_vtc_owner
      from public.vtcs v
      where v.id = old.vtc_id;
    end if;

    if v_old_vtc_owner is not null
       and v_old_vtc_owner = v_uid
       and (new.vtc_id is distinct from old.vtc_id
            or new.vtc_role is distinct from old.vtc_role) then
      raise exception '车队所有者不能通过客户端离开车队或变更自己的车队身份；请先转让/解散车队（需 service_role）'
        using errcode = '42501';
    end if;

    if new.vtc_id is null then
      -- 退出车队：两个字段必须同时清空
      if new.vtc_role is not null then
        raise exception '退出车队时必须同时把 vtc_role 置空'
          using errcode = '42501';
      end if;
    else
      -- 新加入车队（原来不在任何车队）必须是已验证用户；已在队内改资料/改名不受影响
      if old.vtc_id is null and new.vtc_id is distinct from old.vtc_id
         and not public.rct_is_steam_verified() then
        raise exception '未完成 Steam 正版验证，不能加入车队'
          using errcode = '42501';
      end if;
      -- 合法取值
      if new.vtc_role is null
         or new.vtc_role not in ('owner', 'vice_owner', 'dispatcher', 'member') then
        raise exception '非法 vtc_role：%，只允许 owner / vice_owner / dispatcher / member',
          coalesce(new.vtc_role, '(null)')
          using errcode = '42501';
      end if;

      -- 目标车队必须真实存在
      select v.owner_id, coalesce(v.is_recruiting, true)
        into v_vtc_owner, v_recruiting
      from public.vtcs v
      where v.id = new.vtc_id;

      if not found then
        raise exception '目标车队不存在（vtc_id=%），禁止把资料写成不存在的车队', new.vtc_id
          using errcode = '42501';
      end if;

      -- 禁止自称 owner：必须真的是该车队的 owner_id（建队流程天然满足）
      -- 注意：不看 role_level —— 即使是工作人员/经理也不能通过客户端把
      -- 自己“写成”某个车队的 owner（否则会伪造 owner 徽章）。
      if new.vtc_role = 'owner'
         and v_vtc_owner is distinct from v_uid then
        raise exception '禁止把自己写成车队 owner：你不是该车队的 owner_id'
          using errcode = '42501';
      end if;

      -- 副队长/调度员只能由车队管理 RPC（车队所有者）任命，客户端不能自己设置
      if new.vtc_role in ('vice_owner', 'dispatcher') then
        raise exception '副队长/调度员只能由车队所有者任命'
          using errcode = '42501';
      end if;

      -- 新加入的车队必须仍在招募（已在队内改名/改角色不受影响）
      if old.vtc_id is distinct from new.vtc_id
         and v_recruiting is false then
        raise exception '该车队当前未开放招募（is_recruiting = false）'
          using errcode = '42501';
      end if;
    end if;
  end if;

  -- 3.4.7 跨用户编辑的总闸门：不能动同级或上级的整行（含昵称/简介等展示字段），
  --       与后台 UI 的“不可操作”规则保持一致。
  --       例外：Lv.100 开发者可互相管理（交接文档“无视任何限制”，前端也放开）。
  if old.id <> v_uid and v_old_level >= v_level and v_level < 100 then
    raise exception '禁止修改同级或上级的资料（目标 Lv.%，你的 Lv.%）', v_old_level, v_level
      using errcode = '42501';
  end if;

  return new;
end;
$fn$;


