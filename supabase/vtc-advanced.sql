-- 4.1 申请加入（approval 模式）
create or replace function public.rct_vtc_apply(p_vtc_id bigint, p_message text default null)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_uid     uuid := auth.uid();
  v_owner   uuid;
  v_mode    text;
  v_rec     boolean;
  v_cur_vtc bigint;
begin
  if v_uid is null then raise exception '请先登录' using errcode = '42501'; end if;
  if not public.rct_is_steam_verified() then
    raise exception '未完成 Steam 正版验证，不能申请加入车队' using errcode = '42501';
  end if;

  select p.vtc_id into v_cur_vtc from public.profiles p where p.id = v_uid;
  if v_cur_vtc is not null then raise exception '你已经在车队中' using errcode = '42501'; end if;

  select v.owner_id, v.join_mode, coalesce(v.is_recruiting, true)
    into v_owner, v_mode, v_rec
  from public.vtcs v where v.id = p_vtc_id;
  if not found then raise exception '车队不存在'; end if;
  if not v_rec then raise exception '该车队暂未开放招募'; end if;
  if v_mode = 'invite' then raise exception '该车队仅接受邀请加入'; end if;
  if v_mode = 'open' then raise exception '该车队开放直接加入，请使用“立即加入”'; end if;

  if exists (select 1 from public.vtc_applications a where a.user_id = v_uid and a.status = 'pending') then
    raise exception '你已有一条待审核的加入申请';
  end if;

  insert into public.vtc_applications (vtc_id, user_id, message)
  values (p_vtc_id, v_uid, nullif(btrim(coalesce(p_message, '')), ''));

  insert into public.notifications (user_id, actor_id, type, content, link, is_read)
  values (v_owner, v_uid, 'vtc', '有玩家申请加入你的车队，请到车队页审核', '/vtc/' || p_vtc_id::text, false);

  return jsonb_build_object('ok', true);
end
$fn$;

-- 4.2 取消自己的申请
create or replace function public.rct_vtc_cancel_application(p_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_uid uuid := auth.uid();
begin
  if v_uid is null then raise exception '请先登录' using errcode = '42501'; end if;
  update public.vtc_applications
     set status = 'cancelled'
   where id = p_id and user_id = v_uid and status = 'pending';
  if not found then raise exception '申请不存在或已处理'; end if;
  return jsonb_build_object('ok', true);
end
$fn$;

-- 4.3 审核申请（车队管理层）
create or replace function public.rct_vtc_review_application(p_id bigint, p_approve boolean)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_uid      uuid := auth.uid();
  v_vtc_id   bigint;
  v_user_id  uuid;
  v_status   text;
begin
  if v_uid is null then raise exception '请先登录' using errcode = '42501'; end if;

  select a.vtc_id, a.user_id, a.status
    into v_vtc_id, v_user_id, v_status
  from public.vtc_applications a
  where a.id = p_id
  for update;
  if not found then raise exception '申请不存在'; end if;
  if not public.rct_is_vtc_manager(v_vtc_id) then
    raise exception '只有车队所有者/副队长可以审核申请' using errcode = '42501';
  end if;
  if v_status <> 'pending' then raise exception '该申请已被处理'; end if;

  if p_approve then
    if exists (select 1 from public.profiles p where p.id = v_user_id and p.vtc_id is not null) then
      raise exception '申请人已在其他车队，无法通过';
    end if;
    perform set_config('rct.vtc_admin', 'on', true);
    update public.profiles set vtc_id = v_vtc_id, vtc_role = 'member' where id = v_user_id;
    perform set_config('rct.vtc_admin', 'off', true);

    update public.vtc_applications
       set status = 'approved', reviewed_by = v_uid, reviewed_at = now()
     where id = p_id;

    insert into public.notifications (user_id, actor_id, type, content, link, is_read)
    values (v_user_id, v_uid, 'vtc', '你的车队加入申请已通过', '/vtc/' || v_vtc_id::text, false);
  else
    update public.vtc_applications
       set status = 'rejected', reviewed_by = v_uid, reviewed_at = now()
     where id = p_id;

    insert into public.notifications (user_id, actor_id, type, content, link, is_read)
    values (v_user_id, v_uid, 'vtc', '你的车队加入申请未通过', '/vtc/' || v_vtc_id::text, false);
  end if;

  return jsonb_build_object('ok', true);
end
$fn$;

