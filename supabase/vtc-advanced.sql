-- ★ 本文件由项目所有者手动执行（或由 AI 通过 Supabase 管理 API 执行，需先备份）。
-- ★ 设计要点：
--   · 成员关系仍然存放在 profiles.vtc_id / profiles.vtc_role（保持与现有页面兼容），
--     不新建 vtc_members 表，避免全站重构。
--   · 所有“跨用户”的车队操作都必须走 SECURITY DEFINER 的 rct_vtc_* RPC：
--     客户端不能直接改别人的 profiles 行（RLS 也不允许）。
--   · RPC 在事务内用 set_config('rct.vtc_admin','on',true) 打开管理开关，
--     守卫触发器 rct_guard_profiles 识别到该开关后放行车队字段的变更。
--     客户端无法在同一个 PostgREST 请求里设置该 GUC（函数在 pg_catalog，不暴露为 RPC）。
--   · 职位取值：owner / vice_owner（副队长）/ dispatcher（调度员）/ member（车手）。
--   · 加入方式 vtcs.join_mode：open（直接加入）/ approval（申请审批，默认）/ invite（仅邀请）。
-- -----------------------------------------------------------------------------
-- 执行方式：
--   1. 先做一次备份（本项目已完成 backups/ 逻辑备份，见 docs/SECURITY.md）。
--   2. 把末尾 commit; 改成 rollback; 预演一次 → 无报错再改回 commit; 执行。
--   3. 执行后跑文件末尾的 V-VTC 校验。
-- =============================================================================

begin;

set local lock_timeout = '5s';
set local statement_timeout = '60s';


-- =============================================================================
-- STEP 0 · 预检
-- =============================================================================
do $vtc_preflight$
begin
  if to_regclass('public.vtcs') is null or to_regclass('public.profiles') is null then
    raise exception '预检失败：vtcs / profiles 表不存在，请先执行 p0-hardening.sql';
  end if;

  if not exists (
    select 1 from information_schema.columns
    where table_schema='public' and table_name='notifications' and column_name='type'
  ) then
    raise exception '预检失败：notifications.type 列不存在，VTC 通知无法写入';
  end if;

  raise notice 'VTC 预检通过。';
end
$vtc_preflight$;


-- =============================================================================
-- STEP 1 · vtcs.join_mode（加入方式）
-- =============================================================================
alter table public.vtcs
  add column if not exists join_mode text not null default 'approval';

do $vtc_joinmode_check$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'vtcs_join_mode_check'
      and conrelid = 'public.vtcs'::regclass
  ) then
    alter table public.vtcs
      add constraint vtcs_join_mode_check
      check (join_mode in ('open', 'approval', 'invite'));
    raise notice '已添加 vtcs.join_mode 约束（open/approval/invite）';
  else
    raise notice 'vtcs.join_mode 约束已存在，跳过';
  end if;
end
$vtc_joinmode_check$;

-- 历史车队默认走审批制（可被队长在车队设置里改）
update public.vtcs set join_mode = 'approval' where join_mode is null;


-- =============================================================================
-- STEP 2 · 辅助函数：当前用户是否是某车队的“管理层”（owner / vice_owner）
-- =============================================================================
create or replace function public.rct_is_vtc_manager(p_vtc_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $fn$
  select exists (
           select 1 from public.vtcs v
           where v.id = p_vtc_id and v.owner_id = auth.uid()
         )
      or exists (
           select 1 from public.profiles p
           where p.id = auth.uid()
             and p.vtc_id = p_vtc_id
             and p.vtc_role in ('owner', 'vice_owner')
         );
$fn$;

comment on function public.rct_is_vtc_manager(bigint) is
  'RCT MP：当前 JWT 用户是否是给定车队的管理层（owner / vice_owner）。';

-- RLS 策略会以查询者身份调用它
grant execute on function public.rct_is_vtc_manager(bigint) to authenticated, service_role;


-- =============================================================================
-- STEP 3 · 新表：vtc_applications / vtc_invitations + RLS
-- =============================================================================
create table if not exists public.vtc_applications (
  id          bigint generated by default as identity primary key,
  vtc_id      bigint not null references public.vtcs (id) on delete cascade,
  user_id     uuid not null references public.profiles (id) on delete cascade,
  message     text,
  status      text not null default 'pending',
  created_at  timestamptz not null default now(),
  reviewed_by uuid references public.profiles (id) on delete set null,
  reviewed_at timestamptz
);

do $vtc_app_status_check$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'vtc_applications_status_check'
      and conrelid = 'public.vtc_applications'::regclass
  ) then
    alter table public.vtc_applications
      add constraint vtc_applications_status_check
      check (status in ('pending', 'approved', 'rejected', 'cancelled'));
  end if;
end
$vtc_app_status_check$;

-- 一个用户同时只能有一条待处理申请（跨车队）
create unique index if not exists vtc_applications_one_pending_per_user
  on public.vtc_applications (user_id) where status = 'pending';

create index if not exists vtc_applications_vtc_status_idx
  on public.vtc_applications (vtc_id, status, created_at desc);

create table if not exists public.vtc_invitations (
  id              bigint generated by default as identity primary key,
  vtc_id          bigint not null references public.vtcs (id) on delete cascade,
  invited_user_id uuid not null references public.profiles (id) on delete cascade,
  invited_by      uuid references public.profiles (id) on delete set null,
  status          text not null default 'pending',
  created_at      timestamptz not null default now(),
  responded_at    timestamptz
);

do $vtc_inv_status_check$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'vtc_invitations_status_check'
      and conrelid = 'public.vtc_invitations'::regclass
  ) then
    alter table public.vtc_invitations
      add constraint vtc_invitations_status_check
      check (status in ('pending', 'accepted', 'declined', 'cancelled'));
  end if;
end
$vtc_inv_status_check$;

create unique index if not exists vtc_invitations_one_pending
  on public.vtc_invitations (vtc_id, invited_user_id) where status = 'pending';

create index if not exists vtc_invitations_user_idx
  on public.vtc_invitations (invited_user_id, status, created_at desc);

alter table public.vtc_applications enable row level security;
alter table public.vtc_invitations  enable row level security;

-- 申请：本人 / 该车队管理层 / 工作人员(Lv.40+) 可读；写只能走 RPC
drop policy if exists "vtc_applications_select" on public.vtc_applications;
create policy "vtc_applications_select"
  on public.vtc_applications
  for select
  to authenticated
  using (
    user_id = auth.uid()
    or public.rct_is_vtc_manager(vtc_id)
    or public.rct_role_level() >= 40
  );

-- 邀请：被邀请人 / 该车队管理层 / 工作人员 可读；写只能走 RPC
drop policy if exists "vtc_invitations_select" on public.vtc_invitations;
create policy "vtc_invitations_select"
  on public.vtc_invitations
  for select
  to authenticated
  using (
    invited_user_id = auth.uid()
    or public.rct_is_vtc_manager(vtc_id)
    or public.rct_role_level() >= 40
  );

-- 注意：两张表都【不建】INSERT/UPDATE/DELETE 策略 —— 所有写操作只允许经 RPC。
-- 若客户端直接 insert 会因 RLS 拒绝（这是预期）。


