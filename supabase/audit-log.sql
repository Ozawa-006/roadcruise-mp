-- =============================================================================
-- RCT MP · 安全 P1：操作审计日志（audit_log）+ 社区规则初始内容
-- 前置：p0-hardening.sql（RLS/辅助函数）、vtc-advanced.sql
-- -----------------------------------------------------------------------------
-- 1. audit_log 表 + 只读 RLS（Lv.90+ 可查）
-- 2. 审计触发器：profiles / vtcs / events / vtc_news / rules_articles / announcements
--    · 只记录“有意义的字段变化”，避免展示字段的噪音
--    · actor 取 auth.uid()；service_role / SQL Editor 改动的 actor 为空
-- 3. rules_articles 初始内容（仅当表为空时插入，可后台 /admin/rules 编辑）
-- =============================================================================

begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';


-- =============================================================================
-- STEP 1 · audit_log
-- =============================================================================
create table if not exists public.audit_log (
  id          bigint generated by default as identity primary key,
  actor_id    uuid references public.profiles (id) on delete set null,
  actor_label text,
  actor_role  integer,
  action      text not null,
  table_name  text not null,
  target_id   text,
  detail      jsonb,
  created_at  timestamptz not null default now()
);

create index if not exists audit_log_created_idx on public.audit_log (created_at desc);
create index if not exists audit_log_table_created_idx on public.audit_log (table_name, created_at desc);
create index if not exists audit_log_actor_idx on public.audit_log (actor_id, created_at desc);

alter table public.audit_log enable row level security;

-- 只有高级社区经理(Lv.90)+ 可查看；客户端不能写入（触发器以 definer 身份写）
drop policy if exists "audit_log_select_senior" on public.audit_log;
create policy "audit_log_select_senior"
  on public.audit_log
  for select
  to authenticated
  using (public.rct_role_level() >= 90);


-- =============================================================================
-- STEP 2 · 审计触发器
-- =============================================================================
create or replace function public.rct_audit_row()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_actor  uuid := auth.uid();
  v_label  text;
  v_level  integer;
  v_action text := lower(tg_op);
  v_target text;
  v_detail jsonb;
begin
  if tg_table_name = 'profiles' then
    if tg_op = 'UPDATE'
       and new.role is not distinct from old.role
       and new.role_level is not distinct from old.role_level
       and new.custom_id is not distinct from old.custom_id
       and new.steam_id is not distinct from old.steam_id
       and new.steam_verified is not distinct from old.steam_verified
       and new.vtc_id is not distinct from old.vtc_id
       and new.vtc_role is not distinct from old.vtc_role then
      return null;
    end if;

    if tg_op = 'DELETE' then
      v_target := old.id::text;
      v_detail := jsonb_build_object('old', jsonb_build_object(
        'role', old.role, 'role_level', old.role_level, 'custom_id', old.custom_id,
        'steam_id', old.steam_id, 'steam_verified', old.steam_verified,
        'vtc_id', old.vtc_id, 'vtc_role', old.vtc_role));
    elsif tg_op = 'INSERT' then
      v_target := new.id::text;
      v_detail := jsonb_build_object('new', jsonb_build_object(
        'role', new.role, 'role_level', new.role_level, 'custom_id', new.custom_id,
        'steam_id', new.steam_id, 'steam_verified', new.steam_verified,
        'vtc_id', new.vtc_id, 'vtc_role', new.vtc_role));
    else
      v_target := new.id::text;
      v_detail := jsonb_build_object(
        'old', jsonb_build_object(
          'role', old.role, 'role_level', old.role_level, 'custom_id', old.custom_id,
          'steam_id', old.steam_id, 'steam_verified', old.steam_verified,
          'vtc_id', old.vtc_id, 'vtc_role', old.vtc_role),
        'new', jsonb_build_object(
          'role', new.role, 'role_level', new.role_level, 'custom_id', new.custom_id,
          'steam_id', new.steam_id, 'steam_verified', new.steam_verified,
          'vtc_id', new.vtc_id, 'vtc_role', new.vtc_role));
    end if;

  elsif tg_table_name = 'vtcs' then
    if tg_op = 'UPDATE'
       and new.name is not distinct from old.name
       and new.tag is not distinct from old.tag
       and new.owner_id is not distinct from old.owner_id
       and new.join_mode is not distinct from old.join_mode
       and new.is_recruiting is not distinct from old.is_recruiting then
      return null;
    end if;

    if tg_op = 'DELETE' then
      v_target := old.id::text;
      v_detail := jsonb_build_object('old', jsonb_build_object(
        'name', old.name, 'tag', old.tag, 'owner_id', old.owner_id,
        'join_mode', old.join_mode, 'is_recruiting', old.is_recruiting));
    elsif tg_op = 'INSERT' then
      v_target := new.id::text;
      v_detail := jsonb_build_object('new', jsonb_build_object(
        'name', new.name, 'tag', new.tag, 'owner_id', new.owner_id,
        'join_mode', new.join_mode, 'is_recruiting', new.is_recruiting));
    else
      v_target := new.id::text;
      v_detail := jsonb_build_object(
        'old', jsonb_build_object(
          'name', old.name, 'tag', old.tag, 'owner_id', old.owner_id,
          'join_mode', old.join_mode, 'is_recruiting', old.is_recruiting),
        'new', jsonb_build_object(
          'name', new.name, 'tag', new.tag, 'owner_id', new.owner_id,
          'join_mode', new.join_mode, 'is_recruiting', new.is_recruiting));
    end if;

  elsif tg_table_name = 'events' then
    if tg_op = 'UPDATE'
       and new.title is not distinct from old.title
       and new.status is not distinct from old.status
       and new.start_at is not distinct from old.start_at
       and new.capacity is not distinct from old.capacity then
      return null;
    end if;

    if tg_op = 'DELETE' then
      v_target := old.id::text;
      v_detail := jsonb_build_object('old', jsonb_build_object(
        'title', old.title, 'status', old.status, 'start_at', old.start_at, 'capacity', old.capacity));
    elsif tg_op = 'INSERT' then
      v_target := new.id::text;
      v_detail := jsonb_build_object('new', jsonb_build_object(
        'title', new.title, 'status', new.status, 'start_at', new.start_at, 'capacity', new.capacity));
    else
      v_target := new.id::text;
      v_detail := jsonb_build_object(
        'old', jsonb_build_object('title', old.title, 'status', old.status, 'start_at', old.start_at, 'capacity', old.capacity),
        'new', jsonb_build_object('title', new.title, 'status', new.status, 'start_at', new.start_at, 'capacity', new.capacity));
    end if;

  elsif tg_table_name = 'vtc_news' then
    if tg_op = 'DELETE' then
      v_target := old.id::text;
      v_detail := jsonb_build_object('old', jsonb_build_object('vtc_id', old.vtc_id, 'title', old.title));
    elsif tg_op = 'INSERT' then
      v_target := new.id::text;
      v_detail := jsonb_build_object('new', jsonb_build_object('vtc_id', new.vtc_id, 'title', new.title));
    else
      v_target := new.id::text;
      v_detail := jsonb_build_object(
        'old', jsonb_build_object('vtc_id', old.vtc_id, 'title', old.title),
        'new', jsonb_build_object('vtc_id', new.vtc_id, 'title', new.title));
    end if;

  elsif tg_table_name = 'rules_articles' then
    if tg_op = 'DELETE' then
      v_target := old.id::text;
      v_detail := jsonb_build_object('old', jsonb_build_object('section', old.section, 'title', old.title, 'status', old.status));
    elsif tg_op = 'INSERT' then
      v_target := new.id::text;
      v_detail := jsonb_build_object('new', jsonb_build_object('section', new.section, 'title', new.title, 'status', new.status));
    else
      v_target := new.id::text;
      v_detail := jsonb_build_object(
        'old', jsonb_build_object('section', old.section, 'title', old.title, 'status', old.status),
        'new', jsonb_build_object('section', new.section, 'title', new.title, 'status', new.status));
    end if;

  elsif tg_table_name = 'announcements' then
    if tg_op = 'DELETE' then
      v_target := old.id::text;
      v_detail := jsonb_build_object('old', jsonb_build_object('title', old.title, 'type', old.type));
    elsif tg_op = 'INSERT' then
      v_target := new.id::text;
      v_detail := jsonb_build_object('new', jsonb_build_object('title', new.title, 'type', new.type));
    else
      v_target := new.id::text;
      v_detail := jsonb_build_object(
        'old', jsonb_build_object('title', old.title, 'type', old.type),
        'new', jsonb_build_object('title', new.title, 'type', new.type));
    end if;

  else
    return null;
  end if;

  select p.display_name, p.role_level
    into v_label, v_level
  from public.profiles p
  where p.id = v_actor;

  insert into public.audit_log (actor_id, actor_label, actor_role, action, table_name, target_id, detail)
  values (v_actor, v_label, v_level, v_action, tg_table_name, v_target, v_detail);

  return null;
end
$fn$;

-- 逐个表挂 AFTER 触发器（幂等）
drop trigger if exists trg_audit_profiles on public.profiles;
create trigger trg_audit_profiles
  after insert or update or delete on public.profiles
  for each row execute function public.rct_audit_row();

drop trigger if exists trg_audit_vtcs on public.vtcs;
create trigger trg_audit_vtcs
  after insert or update or delete on public.vtcs
  for each row execute function public.rct_audit_row();

drop trigger if exists trg_audit_events on public.events;
create trigger trg_audit_events
  after insert or update or delete on public.events
  for each row execute function public.rct_audit_row();

drop trigger if exists trg_audit_vtc_news on public.vtc_news;
create trigger trg_audit_vtc_news
  after insert or update or delete on public.vtc_news
  for each row execute function public.rct_audit_row();

drop trigger if exists trg_audit_rules_articles on public.rules_articles;
create trigger trg_audit_rules_articles
  after insert or update or delete on public.rules_articles
  for each row execute function public.rct_audit_row();

drop trigger if exists trg_audit_announcements on public.announcements;
create trigger trg_audit_announcements
  after insert or update or delete on public.announcements
  for each row execute function public.rct_audit_row();


