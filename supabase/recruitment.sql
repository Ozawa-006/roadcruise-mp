-- =============================================================================
-- RCT MP · 招募系统（设置 + 申请）
-- 前置：p0-hardening.sql（RLS/辅助函数/通知表）
-- -----------------------------------------------------------------------------
-- recruitment_settings：单行配置，站长/管理层可开启或关闭招募
-- recruitment_applications：玩家申请，管理层审核，状态变化通知申请人
-- =============================================================================

begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';

do $rec_preflight$
begin
  if to_regclass('public.profiles') is null or to_regclass('public.notifications') is null then
    raise exception '预检失败：请先执行 p0-hardening.sql';
  end if;
  if not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                 where n.nspname = 'public' and p.proname = 'rct_is_steam_verified') then
    raise exception '预检失败：rct_is_steam_verified() 不存在';
  end if;
  raise notice '招募系统预检通过。';
end
$rec_preflight$;

-- =============================================================================
-- STEP 1 · 设置（单行）
-- =============================================================================
create table if not exists public.recruitment_settings (
  id           smallint primary key default 1 check (id = 1),
  is_open      boolean not null default false,
  title        text not null default '加入 RCT MP 团队',
  intro        text not null default '',
  requirements text not null default '',
  positions    text not null default '',
  updated_by   uuid references public.profiles (id) on delete set null,
  updated_at   timestamptz not null default now()
);

insert into public.recruitment_settings (id) values (1)
on conflict (id) do nothing;

alter table public.recruitment_settings enable row level security;

drop policy if exists "recruitment_settings_select_public" on public.recruitment_settings;
create policy "recruitment_settings_select_public"
  on public.recruitment_settings
  for select
  to anon, authenticated
  using (true);

drop policy if exists "recruitment_settings_update_staff" on public.recruitment_settings;
create policy "recruitment_settings_update_staff"
  on public.recruitment_settings
  for update
  to authenticated
  using (public.rct_role_level() >= 40)
  with check (public.rct_role_level() >= 40);

-- =============================================================================
-- STEP 2 · 申请
-- =============================================================================
create table if not exists public.recruitment_applications (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references public.profiles (id) on delete cascade,
  position    text not null,
  contact     text,
  message     text not null default '',
  status      text not null default 'pending',
  handled_by  uuid references public.profiles (id) on delete set null,
  handle_note text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

do $rec_checks$
begin
  if not exists (select 1 from pg_constraint where conname = 'recruitment_applications_status_check'
                   and conrelid = 'public.recruitment_applications'::regclass) then
    alter table public.recruitment_applications
      add constraint recruitment_applications_status_check
      check (status in ('pending', 'reviewing', 'accepted', 'rejected'));
  end if;
end
$rec_checks$;

create index if not exists recruitment_applications_status_idx
  on public.recruitment_applications (status, created_at desc);
create index if not exists recruitment_applications_user_idx
  on public.recruitment_applications (user_id, created_at desc);

-- 同一用户同时只能有一条「待处理/处理中」申请
create unique index if not exists recruitment_applications_active_unique
  on public.recruitment_applications (user_id)
  where status in ('pending', 'reviewing');

alter table public.recruitment_applications enable row level security;

drop policy if exists "recruitment_applications_select_own_or_staff" on public.recruitment_applications;
create policy "recruitment_applications_select_own_or_staff"
  on public.recruitment_applications
  for select
  to authenticated
  using (user_id = auth.uid() or public.rct_role_level() >= 40);

drop policy if exists "recruitment_applications_insert_own" on public.recruitment_applications;
create policy "recruitment_applications_insert_own"
  on public.recruitment_applications
  for insert
  to authenticated
  with check (
    user_id = auth.uid()
    and public.rct_is_steam_verified()
    and exists (
      select 1 from public.recruitment_settings s
      where s.id = 1 and s.is_open = true
    )
  );

drop policy if exists "recruitment_applications_update_staff" on public.recruitment_applications;
create policy "recruitment_applications_update_staff"
  on public.recruitment_applications
  for update
  to authenticated
  using (public.rct_role_level() >= 40)
  with check (public.rct_role_level() >= 40);

-- updated_at 自动维护（复用已有函数）
create or replace function public.rct_touch_updated_at()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $fn$
begin
  new.updated_at := now();
  return new;
end
$fn$;

drop trigger if exists trg_recruitment_settings_touch on public.recruitment_settings;
create trigger trg_recruitment_settings_touch
  before update on public.recruitment_settings
  for each row execute function public.rct_touch_updated_at();

drop trigger if exists trg_recruitment_applications_touch on public.recruitment_applications;
create trigger trg_recruitment_applications_touch
  before update on public.recruitment_applications
  for each row execute function public.rct_touch_updated_at();

-- =============================================================================
-- STEP 3 · 状态变化通知申请人 + 自动填处理人/时间
-- =============================================================================
create or replace function public.rct_recruitment_touch()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $fn$
begin
  if new.status is distinct from old.status then
    new.handled_by := coalesce(new.handled_by, auth.uid());
  end if;
  return new;
end
$fn$;

drop trigger if exists trg_recruitment_touch on public.recruitment_applications;
create trigger trg_recruitment_touch
  before update on public.recruitment_applications
  for each row execute function public.rct_recruitment_touch();

create or replace function public.rct_recruitment_notify()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_label text := case new.status
    when 'reviewing' then '审核中'
    when 'accepted'  then '已通过'
    when 'rejected'  then '未通过'
    else new.status
  end;
begin
  if new.status is distinct from old.status then
    insert into public.notifications (user_id, actor_id, type, content, link, is_read)
    values (
      new.user_id,
      new.handled_by,
      'recruitment',
      '你的团队申请（' || new.position || '）状态已更新为：' || v_label,
      '/recruitment',
      false
    );
  end if;
  return new;
end
$fn$;

drop trigger if exists trg_recruitment_notify on public.recruitment_applications;
create trigger trg_recruitment_notify
  after update on public.recruitment_applications
  for each row execute function public.rct_recruitment_notify();

commit;

-- V-REC-1
select id, is_open, title from public.recruitment_settings;

-- V-REC-2
select c.relname, c.relrowsecurity from pg_class c
join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relname in ('recruitment_settings','recruitment_applications');

-- V-REC-3
select policyname, cmd from pg_policies
where schemaname = 'public' and tablename in ('recruitment_settings','recruitment_applications')
order by tablename, policyname;

