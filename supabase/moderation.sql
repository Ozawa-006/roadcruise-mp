-- =============================================================================
-- RCT MP · 用户警告 / 禁言 / 封禁（moderation_actions）+ 发帖拦截
-- 前置：p0-hardening.sql（RLS/辅助函数/通知表）
-- -----------------------------------------------------------------------------
-- 1. moderation_actions：warning（仅记录）/ mute（禁言）/ ban（封禁）
-- 2. 生效中的 mute / ban 会阻止在论坛、车队新闻、举报、活动报名写入
-- 3. 新建记录时给目标用户发站内通知
-- =============================================================================

begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';

do $mod_preflight$
begin
  if to_regclass('public.profiles') is null or to_regclass('public.notifications') is null then
    raise exception '预检失败：请先执行 p0-hardening.sql';
  end if;
  raise notice 'moderation 预检通过。';
end
$mod_preflight$;

create table if not exists public.moderation_actions (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references public.profiles (id) on delete cascade,
  action     text not null,
  reason     text not null,
  note       text,
  expires_at timestamptz,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  revoked_at timestamptz,
  revoked_by uuid references public.profiles (id) on delete set null
);

do $mod_checks$
begin
  if not exists (select 1 from pg_constraint where conname = 'moderation_actions_action_check'
                   and conrelid = 'public.moderation_actions'::regclass) then
    alter table public.moderation_actions
      add constraint moderation_actions_action_check
      check (action in ('warning', 'mute', 'ban'));
  end if;
end
$mod_checks$;

create index if not exists moderation_actions_user_idx
  on public.moderation_actions (user_id, created_at desc);
create index if not exists moderation_actions_active_idx
  on public.moderation_actions (action, revoked_at, expires_at);

alter table public.moderation_actions enable row level security;

-- 本人可看自己的记录（资料页展示“当前处罚”）；Lv.40+ 可看全部
drop policy if exists "moderation_select_own_or_staff" on public.moderation_actions;
create policy "moderation_select_own_or_staff"
  on public.moderation_actions
  for select
  to authenticated
  using (user_id = auth.uid() or public.rct_role_level() >= 40);

drop policy if exists "moderation_insert_staff" on public.moderation_actions;
create policy "moderation_insert_staff"
  on public.moderation_actions
  for insert
  to authenticated
  with check (public.rct_role_level() >= 40);

drop policy if exists "moderation_update_staff" on public.moderation_actions;
create policy "moderation_update_staff"
  on public.moderation_actions
  for update
  to authenticated
  using (public.rct_role_level() >= 40)
  with check (public.rct_role_level() >= 40);

-- 不提供 DELETE 策略（处罚记录保留，只能撤销）

-- =============================================================================
-- 是否处于限制写入状态
-- =============================================================================
create or replace function public.rct_is_moderation_blocked(p_user uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $fn$
  select exists (
    select 1
    from public.moderation_actions m
    where m.user_id = p_user
      and m.action in ('mute', 'ban')
      and m.revoked_at is null
      and m.created_at <= now()
      and (m.expires_at is null or m.expires_at > now())
  );
$fn$;

create or replace function public.rct_guard_moderation()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
begin
  if auth.uid() is not null and public.rct_is_moderation_blocked(auth.uid()) then
    raise exception '你当前已被禁言或封禁，暂时无法发布内容' using errcode = '42501';
  end if;
  return new;
end
$fn$;

drop trigger if exists trg_guard_moderation_topics on public.forum_topics;
create trigger trg_guard_moderation_topics
  before insert or update on public.forum_topics
  for each row execute function public.rct_guard_moderation();

drop trigger if exists trg_guard_moderation_replies on public.forum_replies;
create trigger trg_guard_moderation_replies
  before insert or update on public.forum_replies
  for each row execute function public.rct_guard_moderation();

drop trigger if exists trg_guard_moderation_vtc_news on public.vtc_news;
create trigger trg_guard_moderation_vtc_news
  before insert on public.vtc_news
  for each row execute function public.rct_guard_moderation();

drop trigger if exists trg_guard_moderation_reports on public.reports;
create trigger trg_guard_moderation_reports
  before insert on public.reports
  for each row execute function public.rct_guard_moderation();

-- =============================================================================
-- 处罚通知
-- =============================================================================
create or replace function public.rct_moderation_notify()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_label text := case new.action
    when 'warning' then '警告'
    when 'mute'    then '禁言'
    when 'ban'     then '封禁'
    else new.action
  end;
  v_until text := case
    when new.expires_at is null then '长期有效'
    else '至 ' || to_char(new.expires_at, 'YYYY-MM-DD HH24:MI')
  end;
begin
  insert into public.notifications (user_id, actor_id, type, content, link, is_read)
  values (
    new.user_id,
    new.created_by,
    'moderation',
    '你收到一条' || v_label || '：' || new.reason || '（' || v_until || '）',
    '/notifications',
    false
  );
  return new;
end
$fn$;

drop trigger if exists trg_moderation_notify on public.moderation_actions;
create trigger trg_moderation_notify
  after insert on public.moderation_actions
  for each row execute function public.rct_moderation_notify();

commit;

-- V-MOD-1
select c.relname, c.relrowsecurity from pg_class c
join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relname = 'moderation_actions';

-- V-MOD-2
select policyname, cmd from pg_policies
where schemaname = 'public' and tablename = 'moderation_actions' order by 1;

-- V-MOD-3
select tgname, tgrelid::regclass::text as tbl
from pg_trigger
where tgname like 'trg_%moderation%' and not tgisinternal
order by 1;

