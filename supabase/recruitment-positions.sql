-- =============================================================================
-- RCT MP · 招募职位独立开关 + 每职位专属问题
-- 前置：recruitment.sql（设置/申请表）、p0-hardening.sql
-- -----------------------------------------------------------------------------
-- 1. recruitment_positions：每个职位独立 is_open、部门、说明、问题列表、排序
-- 2. recruitment_applications：新增 position_id、answers(jsonb)
-- 3. 申请唯一约束改为「同用户 + 同职位」同时只能有一条待处理/审核中
-- 4. 申请表 INSERT 策略要求：全局开启 + 该职位开启
-- 5. 种子：5 个默认职位 + TMP 风格通用/专属问题（全部默认关闭，由后台开启）
-- =============================================================================

begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';

do $pos_preflight$
begin
  if to_regclass('public.recruitment_settings') is null then
    raise exception '预检失败：请先执行 recruitment.sql';
  end if;
end
$pos_preflight$;

-- =============================================================================
-- STEP 1 · 职位表
-- =============================================================================
create table if not exists public.recruitment_positions (
  id          bigint generated by default as identity primary key,
  name        text not null,
  department  text not null default '',
  description text not null default '',
  questions   jsonb not null default '[]'::jsonb,
  is_open     boolean not null default false,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists recruitment_positions_open_idx
  on public.recruitment_positions (is_open, sort_order);

alter table public.recruitment_positions enable row level security;

drop policy if exists "recruitment_positions_select_public" on public.recruitment_positions;
create policy "recruitment_positions_select_public"
  on public.recruitment_positions
  for select
  to anon, authenticated
  using (true);

drop policy if exists "recruitment_positions_insert_staff" on public.recruitment_positions;
create policy "recruitment_positions_insert_staff"
  on public.recruitment_positions
  for insert
  to authenticated
  with check (public.rct_role_level() >= 40);

drop policy if exists "recruitment_positions_update_staff" on public.recruitment_positions;
create policy "recruitment_positions_update_staff"
  on public.recruitment_positions
  for update
  to authenticated
  using (public.rct_role_level() >= 40)
  with check (public.rct_role_level() >= 40);

drop policy if exists "recruitment_positions_delete_staff" on public.recruitment_positions;
create policy "recruitment_positions_delete_staff"
  on public.recruitment_positions
  for delete
  to authenticated
  using (public.rct_role_level() >= 40);

drop trigger if exists trg_recruitment_positions_touch on public.recruitment_positions;
create trigger trg_recruitment_positions_touch
  before update on public.recruitment_positions
  for each row execute function public.rct_touch_updated_at();

-- =============================================================================
-- STEP 2 · 申请表新增字段 + 唯一约束调整
-- =============================================================================
alter table public.recruitment_applications
  add column if not exists position_id bigint references public.recruitment_positions (id) on delete set null;
alter table public.recruitment_applications
  add column if not exists answers jsonb not null default '{}'::jsonb;

create index if not exists recruitment_applications_position_idx
  on public.recruitment_applications (position_id, status);

-- 旧约束：同一用户只能一条待处理；新约束：同一用户同一职位只能一条待处理
drop index if exists public.recruitment_applications_active_unique;
create unique index if not exists recruitment_applications_active_position_unique
  on public.recruitment_applications (user_id, position_id)
  where status in ('pending', 'reviewing') and position_id is not null;

-- =============================================================================
-- STEP 3 · 申请 INSERT 策略：全局开放 + 职位开放
-- =============================================================================
drop policy if exists "recruitment_applications_insert_own" on public.recruitment_applications;
create policy "recruitment_applications_insert_own"
  on public.recruitment_applications
  for insert
  to authenticated
  with check (
    user_id = auth.uid()
    and public.rct_is_steam_verified()
    and position_id is not null
    and exists (
      select 1 from public.recruitment_settings s
      where s.id = 1 and s.is_open = true
    )
    and exists (
      select 1 from public.recruitment_positions p
      where p.id = position_id and p.is_open = true
    )
  );

-- =============================================================================
-- STEP 4 · 种子职位与问题（仅在职位表为空时写入）
-- =============================================================================
do $pos_seed$
declare
  v_count integer;
  v_common jsonb;
  v_mod jsonb;
  v_event jsonb;
  v_gm jsonb;
  v_support jsonb;
  v_media jsonb;
begin
  select count(*) into v_count from public.recruitment_positions;
  if v_count > 0 then
    raise notice 'recruitment_positions 已有 % 个职位，跳过种子', v_count;
    return;
  end if;

  v_common := jsonb_build_array(
    jsonb_build_object('id','why','label','为什么想申请这个职位？请结合你的动机与期待说明。','type','textarea','required',true),
    jsonb_build_object('id','experience','label','是否有相关经验？请举例说明（社区/版务/活动/技术/作品等）。','type','textarea','required',true),
    jsonb_build_object('id','timezone','label','你的时区与每周可投入时间（例如：UTC+8，每周 5 小时）。','type','text','required',true),
    jsonb_build_object('id','age','label','是否已年满 16 周岁？','type','select','required',true,'options',jsonb_build_array('是','否')),
    jsonb_build_object('id','mic','label','是否有可正常使用的麦克风？','type','select','required',true,'options',jsonb_build_array('是','否'))
  );
  v_mod := v_common || jsonb_build_array(
    jsonb_build_object('id','scenario','label','如果论坛有两名玩家互相人身攻击，你会按什么步骤处理？','type','textarea','required',true)
  );
  v_event := v_common || jsonb_build_array(
    jsonb_build_object('id','event','label','描述一次你组织或参与的活动：规模、你的职责、最终结果。','type','textarea','required',true)
  );
  v_gm := v_common || jsonb_build_array(
    jsonb_build_object('id','rule','label','收到玩家作弊举报后，你会如何核实与处理？','type','textarea','required',true)
  );
  v_support := v_common || jsonb_build_array(
    jsonb_build_object('id','tech','label','描述一次你解决联机/账号/网络问题的经历（问题、排查、结果）。','type','textarea','required',true)
  );
  v_media := v_common || jsonb_build_array(
    jsonb_build_object('id','portfolio','label','请提供作品链接（翻译/视频/图片/直播等）。','type','text','required',false)
  );

  insert into public.recruitment_positions (name, department, description, questions, is_open, sort_order) values
  ('社区版主', '社区线', '负责论坛与 Discord 版务、处理举报与申诉，维护社区氛围。', v_mod, false, 10),
  ('活动策划', '活动线', '规划联运路线、组织官方活动与车队管控，撰写活动公告。', v_event, false, 20),
  ('游戏管理员', '游戏管理线', '游戏内巡查、处理违规与举报，协助维护联运秩序。', v_gm, false, 30),
  ('技术支持', '支持线', '协助新玩家解决联机、账号与技术问题，整理常见问题。', v_support, false, 40),
  ('翻译 / 媒体', '社区线', '翻译公告或制作宣传素材（视频/图片/直播），同步社区信息。', v_media, false, 50);

  raise notice '已写入 5 个默认招募职位（默认关闭，可由后台开启）';
end
$pos_seed$;

commit;

-- V-POS-1
select id, name, department, is_open, jsonb_array_length(questions) as question_count
from public.recruitment_positions order by sort_order;

-- V-POS-2
select policyname, cmd from pg_policies
where schemaname = 'public' and tablename = 'recruitment_positions' order by 1;

-- V-POS-3
select indexname from pg_indexes
where schemaname = 'public' and indexname = 'recruitment_applications_active_position_unique';

