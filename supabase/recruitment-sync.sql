-- =============================================================================
-- RCT MP · 招募通过后同步职位 + 团队职位变更记录 + 实习岗位
-- 前置：recruitment.sql / recruitment-positions.sql
-- -----------------------------------------------------------------------------
-- 1. roles 增加实习职级（实习社区版主/游戏管理员/支持员/翻译/活动执行）
-- 2. recruitment_positions 增加 assign_role（通过后授予角色）、is_trainee、trainee_role
-- 3. team_changes：记录所有职位/等级变更（公开可读，用于论坛「团队变更」）
-- 4. RPC：rct_recruitment_accept（通过并同步职位）、rct_recruitment_promote（实习转正）
-- 5. 守卫补丁：RPC 内 set_config('rct.recruitment_admin','on') 放行 profiles 身份字段更新
-- =============================================================================

