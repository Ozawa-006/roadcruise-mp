set local lock_timeout = '5s';
set local statement_timeout = '60s';

do $sync_preflight$
begin
  if to_regclass('public.recruitment_positions') is null then
    raise exception '预检失败：请先执行 recruitment-positions.sql';
  end if;
end
$sync_preflight$;

-- =============================================================================
