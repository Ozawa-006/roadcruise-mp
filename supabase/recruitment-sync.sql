update public.recruitment_positions set assign_role = 'game_moderator'
  where name = '游戏管理员' and coalesce(assign_role, '') = '';
update public.recruitment_positions set assign_role = 'support'
  where name = '技术支持' and coalesce(assign_role, '') = '';
update public.recruitment_positions set assign_role = 'translator'
  where name = '翻译 / 媒体' and coalesce(assign_role, '') = '';

-- 实习职位（复用对应正式职位的问题）
do $trainee_seed$
declare
  v_item record;
begin
  for v_item in
    select * from (values
      ('实习社区版主', 'community_moderator', 'community_moderation_trainee', '社区线', '社区版主', 60),
      ('实习游戏管理员', 'game_moderator', 'game_moderation_trainee', '游戏管理线', '游戏管理员', 70),
      ('实习支持员', 'support', 'support_trainee', '支持线', '技术支持', 80),
      ('实习翻译', 'translator', 'translator_trainee', '翻译团队', '翻译 / 媒体', 90),
      ('实习活动执行', 'event_team', 'event_trainee', '活动线', '活动策划', 100)
    ) as t(name, assign_role, trainee_role, department, source_name, sort_order)
  loop
    if not exists (select 1 from public.recruitment_positions where name = v_item.name) then
      insert into public.recruitment_positions
        (name, department, description, questions, is_open, sort_order, assign_role, is_trainee, trainee_role)
      select
        v_item.name,
        v_item.department,
        '实习岗位：通过后先进入实习期，表现合格后可转正为「' || v_item.source_name || '」。',
        coalesce((select questions from public.recruitment_positions where name = v_item.source_name), '[]'::jsonb),
        false,
        v_item.sort_order,
        v_item.assign_role,
        true,
        v_item.trainee_role;
    end if;
  end loop;
end
$trainee_seed$;

-- =============================================================================
-- STEP 3 · 团队职位变更记录
-- =============================================================================
create table if not exists public.team_changes (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references public.profiles (id) on delete cascade,
  old_role   text,
  old_level  integer,
  new_role   text,
  new_level  integer,
  change_type text not null default 'promotion',
  actor_id   uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);

do $tc_checks$
begin
  if not exists (select 1 from pg_constraint where conname = 'team_changes_type_check'
                   and conrelid = 'public.team_changes'::regclass) then
    alter table public.team_changes
      add constraint team_changes_type_check
      check (change_type in ('join', 'promotion', 'demotion', 'trainee', 'role_change'));
  end if;
end
$tc_checks$;

create index if not exists team_changes_created_idx on public.team_changes (created_at desc);
create index if not exists team_changes_user_idx on public.team_changes (user_id, created_at desc);

alter table public.team_changes enable row level security;
drop policy if exists "team_changes_select_public" on public.team_changes;
create policy "team_changes_select_public"
  on public.team_changes
  for select
  to anon, authenticated
  using (true);

grant select on public.team_changes to anon, authenticated;

create or replace function public.rct_team_change_record()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_type text;
begin
  if new.role is not distinct from old.role
     and new.role_level is not distinct from old.role_level then
    return new;
  end if;

  v_type := case
    when new.role ilike '%trainee%' then 'trainee'
    when coalesce(new.role_level, 0) > coalesce(old.role_level, 0) then 'promotion'
    when coalesce(new.role_level, 0) < coalesce(old.role_level, 0) then 'demotion'
    else 'role_change'
  end;

  insert into public.team_changes
    (user_id, old_role, old_level, new_role, new_level, change_type, actor_id)
  values
    (new.id, old.role, old.role_level, new.role, new.role_level, v_type, auth.uid());

  return new;
end
$fn$;

drop trigger if exists trg_team_change_record on public.profiles;
create trigger trg_team_change_record
  after update on public.profiles
  for each row execute function public.rct_team_change_record();

-- =============================================================================
-- STEP 4 · 守卫补丁：RPC 内放行身份字段
-- =============================================================================
do $guard_patch$
declare
  v_def text;
begin
  select pg_get_functiondef(p.oid) into v_def
  from pg_proc p
  where p.proname = 'rct_guard_profiles'
    and p.pronamespace = 'public'::regnamespace;

  if position('rct.recruitment_admin' in v_def) = 0 then
    v_def := replace(
      v_def,
      E'\nbegin\n',
      E'\nbegin\n  if coalesce(current_setting(''rct.recruitment_admin'', true), '''') = ''on'' then\n    return new;\n  end if;\n'
    );
    execute v_def;
    raise notice '已给 rct_guard_profiles 增加 recruitment_admin 放行';
  else
    raise notice 'rct_guard_profiles 已包含 recruitment_admin 放行';
  end if;
end
$guard_patch$;

-- =============================================================================
-- STEP 5 · RPC：通过申请并同步职位 / 实习转正
-- =============================================================================
create or replace function public.rct_recruitment_accept(
  p_application_id bigint,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_uid    uuid := auth.uid();
  v_level  integer := public.rct_role_level();
  v_app    record;
  v_role   text;
  v_role_level integer;
begin
  if v_uid is null then raise exception '请先登录' using errcode = '42501'; end if;
  if v_level < 40 then raise exception '权限不足：需要 Lv.40+ 才能处理申请' using errcode = '42501'; end if;

  select a.id, a.user_id, a.status, a.position,
         p.assign_role, p.is_trainee, p.trainee_role
    into v_app
  from public.recruitment_applications a
  left join public.recruitment_positions p on p.id = a.position_id
  where a.id = p_application_id
  for update of a;

  if not found then raise exception '申请不存在'; end if;
  if v_app.status not in ('pending', 'reviewing') then
    raise exception '该申请已处理，不能重复通过';
  end if;

  v_role := case when v_app.is_trainee then v_app.trainee_role else v_app.assign_role end;

  if v_role is not null and v_role <> '' then
    select level into v_role_level from public.roles where name = v_role;
    if v_role_level is null then
      raise exception '职位角色不存在：%', v_role;
    end if;

    -- 放行 profiles 守卫（仅本事务）
    perform set_config('rct.recruitment_admin', 'on', true);
    update public.profiles
       set role = v_role,
           role_level = v_role_level
     where id = v_app.user_id;
  end if;

  update public.recruitment_applications
     set status = 'accepted',
         handled_by = coalesce(handled_by, v_uid),
         handle_note = coalesce(nullif(btrim(coalesce(p_note, '')), ''), handle_note)
   where id = p_application_id;

  return jsonb_build_object(
    'ok', true,
    'role', v_role,
    'role_level', v_role_level,
    'trainee', coalesce(v_app.is_trainee, false)
  );
end
$fn$;

create or replace function public.rct_recruitment_promote(p_application_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  v_uid   uuid := auth.uid();
  v_level integer := public.rct_role_level();
  v_app   record;
  v_role  text;
  v_role_level integer;
begin
  if v_uid is null then raise exception '请先登录' using errcode = '42501'; end if;
  if v_level < 40 then raise exception '权限不足' using errcode = '42501'; end if;

  select a.id, a.user_id, a.status, p.assign_role, p.is_trainee
    into v_app
  from public.recruitment_applications a
  left join public.recruitment_positions p on p.id = a.position_id
  where a.id = p_application_id
  for update of a;

  if not found then raise exception '申请不存在'; end if;
  if v_app.status <> 'accepted' then raise exception '只有已通过的申请才能转正'; end if;
  if v_app.assign_role is null or v_app.assign_role = '' then
    raise exception '该职位没有配置正式角色，无法转正';
  end if;

  select level into v_role_level from public.roles where name = v_app.assign_role;
  if v_role_level is null then raise exception '角色不存在：%', v_app.assign_role; end if;

  perform set_config('rct.recruitment_admin', 'on', true);
  update public.profiles
     set role = v_app.assign_role,
         role_level = v_role_level
   where id = v_app.user_id;

  update public.recruitment_applications
     set handle_note = concat_ws('；', nullif(handle_note, ''), '已转正')
   where id = p_application_id;

  return jsonb_build_object('ok', true, 'role', v_app.assign_role, 'role_level', v_role_level);
end
$fn$;

commit;

