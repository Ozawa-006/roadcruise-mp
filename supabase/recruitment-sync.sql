  ('game_moderation_trainee', '实习游戏管理员 (Game Moderation Trainee)', 20, '游戏管理线'),
  ('support_trainee', '实习支持员 (Support Trainee)', 20, '支持线'),
  ('translator_trainee', '实习翻译 (Translator Trainee)', 20, '翻译团队'),
  ('event_trainee', '实习活动执行 (Event Trainee)', 20, '活动线')
on conflict (name) do update
  set display_name = excluded.display_name,
      level = excluded.level,
      department = excluded.department;

